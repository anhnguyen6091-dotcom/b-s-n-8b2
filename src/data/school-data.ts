export interface PeriodLesson {
  period: number; // 1 -> 5
  time: string;   // Ví dụ: 07:15 - 08:00
  subject: string;
  teacher: string;
  room?: string;
  type: "stem" | "humanities" | "language" | "pe" | "activity";
}

export type DayOfWeek = "monday" | "tuesday" | "wednesday" | "thursday" | "friday" | "saturday";

export interface DaySchedule {
  dayId: DayOfWeek;
  dayName: string; // "Thứ Hai", "Thứ Ba", ...
  shortName: string; // "T2", "T3", ...
  lessons: PeriodLesson[];
}

export interface HomeroomTeacher {
  name: string;
  subject: string;
  email: string;
  phone: string;
  officeHours: string;
  message: string;
  avatarColor: string;
}

export interface SchoolClass {
  id: string; // slug, e.g. "10a1"
  name: string; // "10A1"
  grade: 10 | 11 | 12;
  academicTrack: "Khoa học Tự nhiên" | "Khoa học Xã hội" | "Song ngữ - Quốc tế";
  room: string;
  studentCount: number;
  classPresident: string;
  secretary: string;
  teacher: HomeroomTeacher;
  schedule: DaySchedule[];
}

